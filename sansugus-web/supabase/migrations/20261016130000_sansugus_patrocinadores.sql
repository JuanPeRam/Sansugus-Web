-- ════════════════════════════════════════════════════════════════════════════
-- SANSUGUS FC · Patrocinadores
-- Se gestionan desde Panel → Patrocinadores y la web los muestra en Inicio y en
-- el pie de página, en el orden indicado. Los logos se suben al bucket `sansugus`
-- (carpeta patrocinadores/); los dos iniciales apuntan a los ficheros de la web.
-- ════════════════════════════════════════════════════════════════════════════

create table if not exists sansugus.patrocinadores (
  id         int generated by default as identity primary key,
  nombre     text not null check (btrim(nombre) <> ''),
  logo_url   text,
  web_url    text,
  orden      int not null default 0,
  activo     boolean not null default true,  -- visible en la web
  monocromo  boolean not null default true,  -- logo en blanco (como en la rejilla de la web)
  creado     timestamptz not null default now()
);
create index if not exists patrocinadores_orden_idx on sansugus.patrocinadores (orden, id);

-- ─── Seguridad: lectura pública, escritura solo para administradores ────────
alter table sansugus.patrocinadores enable row level security;
create policy "lectura publica" on sansugus.patrocinadores for select to anon, authenticated using (true);
create policy "admins escriben" on sansugus.patrocinadores for all to authenticated using (public.is_admin()) with check (public.is_admin());
grant select on sansugus.patrocinadores to anon, authenticated;
grant insert, update, delete on sansugus.patrocinadores to authenticated;
grant all on sansugus.patrocinadores to service_role;
grant usage, select on sequence sansugus.patrocinadores_id_seq to authenticated, service_role;

-- Los logos suelen venir en SVG: el bucket también los admite
update storage.buckets
set allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'image/svg+xml']
where id = 'sansugus';

-- Patrocinadores actuales (los que había fijos en el pie de la web)
insert into sansugus.patrocinadores (nombre, logo_url, web_url, orden)
select v.nombre, v.logo_url, v.web_url, v.orden
from (values
  ('Dos Puntos Real Estate', '/resources/img/sponsors/dospuntos.png', 'https://www.2puntos.es', 1),
  ('Ascensores Insanz', '/resources/img/sponsors/insanz.svg', 'https://ascensoresinsanz.wordpress.com/', 2)
) as v(nombre, logo_url, web_url, orden)
where not exists (select 1 from sansugus.patrocinadores);

notify pgrst, 'reload schema';
